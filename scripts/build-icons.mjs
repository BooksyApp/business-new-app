#!/usr/bin/env node
// One source of truth for icons: packages/shared/icons/svg/<name>.svg (+ <name>-bold.svg).
// Generates apps/mobile/src/theme/iconData.ts (mobile only; the web restyle keeps its own icons).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const LIB = path.join(ROOT, 'packages/shared/icons');
const SVG = path.join(LIB, 'svg');
const OUT = { mobile: path.join(ROOT, 'apps/mobile/src/theme/iconData.ts') };
const fail = (m) => { console.error(`\nicons: ${m}\n`); process.exit(1); };
const num = (s) => Number(s);

// ---- parse + validate one svg file -> { d, evenodd } ----
function parse(file) {
  const src = fs.readFileSync(file, 'utf8');
  const rel = path.relative(ROOT, file);
  const root = /<svg\b([^>]*)>/.exec(src);
  if (!root) fail(`${rel}: no <svg> element`);
  const vb = /viewBox="([^"]*)"/.exec(root[1]);
  if (!vb || vb[1].trim().replace(/\s+/g, ' ') !== '0 0 24 24') fail(`${rel}: viewBox must be "0 0 24 24" (found ${vb ? `"${vb[1]}"` : 'none'})`);
  if (/\s(width|height)="/.test(root[1])) fail(`${rel}: remove width/height from <svg> (size is set by the app)`);
  const bad = [...src.matchAll(/\b(fill|stroke|color|stop-color)\s*[=:]\s*"?'?\s*([^"';\s>]+)/g)].find((m) => !['none', 'currentColor', 'inherit'].includes(m[2]));
  if (bad) fail(`${rel}: hard-coded colour "${bad[0].trim()}"; use currentColor (or fill="none")`);
  const body = src.slice(root[0].length);
  const ds = []; let evenodd = false; let n = 0;
  for (const m of body.matchAll(/<(\w+)\b([^>]*?)\/?>/g)) {
    const [, tag, a] = m;
    if (tag === 'path') { const d = /\sd="([^"]+)"/.exec(a); if (!d) fail(`${rel}: <path> without d`); ds.push(d[1].trim()); if (/evenodd/.test(a)) evenodd = true; n++; }
    else if (tag === 'circle') { const g = (k) => num(new RegExp(`\\s${k}="([^"]+)"`).exec(a)?.[1]); const r = g('r'), cx = g('cx'), cy = g('cy'); ds.push(`M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0`); n++; }
    else if (tag === 'line') { const g = (k) => num(new RegExp(`\\s${k}="([^"]+)"`).exec(a)?.[1] ?? 0); ds.push(`M${g('x1')} ${g('y1')}L${g('x2')} ${g('y2')}`); n++; }
    else if (!['g', 'svg', 'title', 'desc'].includes(tag)) fail(`${rel}: unsupported <${tag}>; convert it to a <path> (Figma: Outline stroke / Flatten)`);
  }
  if (!n) fail(`${rel}: no shapes`);
  return { d: ds.join(' '), evenodd };
}

// ---- read library ----
const files = fs.readdirSync(SVG).filter((f) => f.endsWith('.svg')).sort();
const names = [...new Set(files.map((f) => f.replace(/(-bold)?\.svg$/, '')))].sort();
const icons = {};
for (const n of names) {
  if (!files.includes(`${n}.svg`)) fail(`${n}-bold.svg has no ${n}.svg`);
  const r = parse(path.join(SVG, `${n}.svg`));
  const b = files.includes(`${n}-bold.svg`) ? parse(path.join(SVG, `${n}-bold.svg`)) : null;
  icons[n] = { r: r.d, b: b ? b.d : null, ev: b ? b.evenodd : false };
}

const write = (p, s) => { fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, s); };
// ---- mobile ----
let ts = `// GENERATED by scripts/build-icons.mjs from packages/shared/icons/svg - do not edit; run \`npm run icons\`.
// Solar Icon Set by 480 Design (https://www.figma.com/community/file/1166831539721848736), licensed CC BY 4.0.
// [rest, active, noBold] path data, viewBox 0 0 24 24. Rest = stroke 1.5 round caps/joins, no fill.
// Active = filled Bold twin (evenodd); noBold=1: no Bold file exists, the rest glyph is stroked again in the active colour.
export const ICONS: Record<string, [string, string, 0 | 1]> = {\n`;
for (const n of names) ts += `  ${JSON.stringify(n)}: [${JSON.stringify(icons[n].r)}, ${JSON.stringify(icons[n].b ?? icons[n].r)}, ${icons[n].b ? 0 : 1}],\n`;
write(OUT.mobile, ts + '};\n');


console.log(`icons: ${names.length} icons -> mobile iconData.ts`);
